// Comprueba bundle e interacciones en Electron con un perfil de prueba aislado.
const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const output = path.join(__dirname, '..', '.research');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'smoke-profile'));
let done=false;
const timer=setTimeout(()=>{if(!done){console.error('Electron no completó las interacciones en 60 segundos.');app.exit(1);}},60000);
app.whenReady().then(async()=>{
  const errors=[];
  const win=new BrowserWindow({show:false,width:1500,height:960,webPreferences:{preload:path.join(__dirname,'../desktop/preload.cjs'),contextIsolation:true,nodeIntegration:false,sandbox:true,backgroundThrottling:false}});
  win.webContents.on('console-message',(_event,level,message)=>{if(level===3)errors.push(message);});
  try{
    await win.loadFile(path.join(__dirname,'../dist/index.html'));
    const result=await win.webContents.executeJavaScript(`({title:document.title,canvas:!!document.querySelector('#scene canvas'),assets:document.querySelectorAll('[data-asset]').length,bridge:typeof window.habita?.saveProject==='function'&&typeof window.habita?.openProject==='function',stats:document.querySelector('#project-stats')?.textContent})`);
    console.log('Bundle cargado; comprobando edición y luces.');
    if(!result.canvas||result.assets!==32||!result.bridge||errors.length)throw new Error(JSON.stringify({result,errors}));
    const interactions=await win.webContents.executeJavaScript(`(async()=>{
      const $=s=>document.querySelector(s),check=(value,message)=>{if(!value)throw Error(message);};
      const wait=()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
      $('#focus-mode').click();await wait();
      check(getComputedStyle($('.library')).display==='none','El modo ampliado debe ocultar la biblioteca');
      $('#focus-mode').click();await wait();
      check(getComputedStyle($('.library')).display!=='none','La biblioteca debe regresar');
      $('[data-asset="sofa"]').click();await wait();
      check(!$('.selection-actions').hidden,'Barra contextual visible');
      const rotation=()=>Number($('[data-field="rotation"]').value),before=rotation();
      $('[data-action="rotate"]').click();await wait();
      check(rotation()===(before+90)%360,'Girar desde la maqueta');
      $('#undo').click();await wait();
      // Deshacer limpia la selección: volver a seleccionar con una nueva incorporación.
      $('[data-asset="sofa"]').click();await wait();
      const count=()=>Number($('#project-stats').textContent.match(/(\\d+) objetos/)[1]),initial=count();
      $('[data-action="duplicate"]').click();await wait();check(count()===initial+1,'Duplicar desde la maqueta');
      $('#undo').click();await wait();check(count()===initial,'Deshacer duplicación');
      $('[data-asset="sofa"]').click();await wait();$('[data-action="focus"]').click();await wait();
      const rect=$('.selection-actions').getBoundingClientRect(),viewport=$('.viewport').getBoundingClientRect();
      check(rect.left>=viewport.left&&rect.right<=viewport.right,'La barra debe quedar dentro de la maqueta');
      $('[data-view="walk"]').click();await wait();check($('.selection-actions').hidden,'Ocultar barra en recorrido');
      $('[data-view="3d"]').click();await wait();
      const sound=$('#sound-toggle'),original=sound.getAttribute('aria-pressed');sound.click();
      check(sound.getAttribute('aria-pressed')!==original,'Preferencia de sonido');sound.click();
      $('[data-action="close"]').click();check($('.selection-actions').hidden,'Cerrar selección');
      // Restablecer la casa de ejemplo para que la captura no contenga los objetos de prueba.
      localStorage.removeItem('habita-project');
      return {focus:true,rotate:true,duplicateUndo:true,contextBounds:true,walk:true,sound:true};
    })()`);
    fs.writeFileSync(path.join(output,'interaction-preview.png'),(await win.webContents.capturePage()).toPNG());
    await win.loadFile(path.join(__dirname,'../dist/index.html'));
    const lighting=await win.webContents.executeJavaScript(`(async()=>{
      const $=s=>document.querySelector(s),check=(value,message)=>{if(!value)throw Error(message);};
      const wait=()=>new Promise(resolve=>setTimeout(resolve,350));
      $('[data-asset="floor-lamp"]').click();await wait();
      const saved=()=>JSON.parse(localStorage.getItem('habita-project'));
      const id=saved().items.at(-1).id,light=()=>saved().items.find(i=>i.id===id).light;
      const range=$('[data-light="brightness"]');range.value='27';range.dispatchEvent(new Event('input'));
      check(!light(),'La previsualización no debe guardar ni crear historial');
      range.dispatchEvent(new Event('change'));await wait();check(light().brightness===27,'Guardar intensidad');
      $('#undo').click();await wait();check(!light(),'Deshacer un gesto de intensidad completo');
      $('#redo').click();await wait();check(light().brightness===27,'Rehacer intensidad');
      document.querySelectorAll('[data-select-lamp]').forEach(b=>{if(b.dataset.selectLamp===id)b.click();});
      const warmth=$('[data-light="warmth"]');warmth.value='20';warmth.dispatchEvent(new Event('input'));warmth.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
      check(Number(warmth.value)===72,'Escape cancela la calidez');
      $('[data-mode="color"]').click();await wait();$('[data-light-color="#88baff"]').click();await wait();
      check(light().mode==='color'&&light().color==='#88baff','Guardar color individual');
      $('.light-power').click();await wait();check(!light().on,'Apagar lámpara');
      $('#undo').click();await wait();check(light().on,'Deshacer encendido');
      $('#room-chips [data-room="living"]').click();await wait();
      check($('.room-lighting')?.textContent.includes('Luces de este espacio'),'Controles de habitación');
      $('[data-lights="off"]').click();await wait();check(!light().on,'Apagar luces del espacio');
      $('#undo').click();await wait();check(light().on,'Deshacer el grupo en un paso');
      document.querySelectorAll('[data-select-lamp]').forEach(b=>{if(b.dataset.selectLamp===id)b.click();});
      $('[data-action="focus"]').click();await wait();
      check(!!$('.light-power')&&!$('.selection-actions').hidden,'Seleccionar una lámpara desde el listado');
      await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
      return {id,preview:true,brightnessUndo:true,color:true,power:true,roomGroupUndo:true};
    })()`);
    fs.writeFileSync(path.join(output,'lighting-preview.png'),(await win.webContents.capturePage()).toPNG());
    await win.loadFile(path.join(__dirname,'../dist/index.html'));
    const reopened=await win.webContents.executeJavaScript(`(()=>{const project=JSON.parse(localStorage.getItem('habita-project'));return project.items.find(i=>i.id===${JSON.stringify(lighting.id)})?.light;})()`);
    if(reopened?.brightness!==27||reopened?.color!=='#88baff'||!reopened?.on)throw Error('No se conservaron las luces al abrir');
    await win.webContents.executeJavaScript('localStorage.removeItem("habita-project")');
    await win.loadFile(path.join(__dirname,'../dist/index.html'));
    await win.webContents.executeJavaScript('document.fonts.ready');
    await win.webContents.executeJavaScript('Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{})))');
    const capture=await win.webContents.capturePage();fs.writeFileSync(path.join(output,'desktop-preview.png'),capture.toPNG());
    if(errors.length)throw Error(JSON.stringify(errors));
    console.log(JSON.stringify({status:'passed',...result,interactions,lighting,reopened,errors}));done=true;clearTimeout(timer);app.exit(0);
  }catch(error){console.error(error);done=true;clearTimeout(timer);app.exit(1);}
});
